export function ToolIcon({ iconKey, fallbackUrl, className = '', size = 56 }: Props) {
  const cfg = iconKey ? BRAND[iconKey] : null;

  if (!cfg && fallbackUrl) {
    try {
      const host = new URL(fallbackUrl).hostname;
      const fav = `https://www.google.com/s2/favicons?domain=${host}&sz=128`;
      return (
        <div
          className={`rounded-full bg-white border border-border/60 grid place-items-center overflow-hidden ${className}`}
          style={{ width: size, height: size }}
        >
          <img src={fav} alt="" className="w-1/2 h-1/2 object-contain" />
        </div>
      );
    } catch {
      // fall through
    }
  }

  const c = cfg ?? BRAND.globe;
  return (
    <div
      className={`rounded-full grid place-items-center shrink-0 ${c.bg} ${className}`}
      style={{ width: size, height: size }}
      aria-label={c.label}
    >
      {c.svg}
    </div>
  );
}

